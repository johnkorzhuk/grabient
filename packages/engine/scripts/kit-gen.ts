/* `pnpm kit:gen`: each field effect's kernel compiled (kit/compile.ts) into the files the kit ships, which nothing
   compiles at run time:
   - kit/gen/<kind>.ts: the kernel in GLSL ES 3.00 (the player and the WebGL page) and in WGSL (the WebGPU page), and
     its cost an evaluation;
   - video/kit-kernels.c: every kernel in C for the clips' module, which includes it (video.wasm is built from it), and
     kit/gen/kernel-order.ts, the kinds in the order of its table of kernels, with their costs and their shadows' runs
     (kitShadowRun), which their clips are weighed by;
   - kit/gen/drawings.ts: each site effect's drawing (kitDrawing), which names its cards, pictures and clips kept;
   - kit/gen/kind-steps.ts: each site effect's steps (types.ts FieldEffect.steps), which effect.ts's EFFECT_KINDS reads
     for every page's start, so no page loads a definition to know which effects take the view's steps.
   kit/compile.test.ts fails while any of them differs from what this writes. */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { type CompiledKernel, compileKernel, KIT_KERNEL_BUDGET } from "../src/kit/compile.ts";
import demo from "../src/kit/fields/demo.ts";
import { KIT_KINDS } from "../src/kit/kinds.ts";
import { kitEffect } from "../src/kit/registry.ts";
import { KIT_EDGE, kitRng } from "../src/kit/scene.ts";
import type { FieldEffect } from "../src/kit/types.ts";

/** The field effects whose kernels are compiled, each from kit/fields/<kind>.ts: the kit's demo, which the kit's tests
    draw in every format, then the site's (kit/registry.ts). */
export const KIT_FIELDS: readonly FieldEffect[] = [demo, ...KIT_KINDS.map(kitEffect)];

/** packages/engine/src, which every generated file's path is relative to */
export const ENGINE_SRC = new URL("../src/", import.meta.url);

const template = (code: string) => `\`${code.replace(/[\\`]|\$\{/g, m => `\\${m}`)}\``;

function kindFile(def: FieldEffect, k: CompiledKernel): string {
  return `/* Generated by \`pnpm kit:gen\` (kit/compile.ts) from kit/fields/${def.kind}.ts: edit that file, never this one.
   ${def.field.name}, the effect's kernel, in GLSL ES 3.00 (the player, the WebGL page) and in WGSL (the WebGPU page),
   and its cost an evaluation. */
export const KERNEL_GLSL = ${template(k.glsl)};

export const KERNEL_WGSL = ${template(k.wgsl)};

export const KERNEL_COST = ${k.cost};
`;
}

/** Biome's form of a list of numbers: on one line where it fits, else as many to a line as fit. */
function numberList(head: string, values: readonly number[]): string {
  const line = `${head} = [${values.join(", ")}];`;
  if (line.length <= 100) return line;
  const rows: string[] = [];
  values.forEach((v, n) => {
    const item = n < values.length - 1 ? `${v},` : `${v}`;
    const last = rows.length - 1;
    if (last >= 0 && rows[last].length + 1 + item.length <= 100) rows[last] += ` ${item}`;
    else rows.push(`  ${item}`);
  });
  return `${head} = [\n${rows.join("\n")}\n];`;
}

/** kernel-order.ts: the kinds in Biome's form of a list of names, on one line where it fits, else one name a line, then
    their kernels' costs and their shadows' runs. */
function orderFile(kinds: string[], costs: number[], runs: number[]): string {
  const line = `export const KIT_KERNEL_KINDS = [${kinds.map(k => `"${k}"`).join(", ")}] as const;`;
  const list =
    line.length <= 100
      ? line
      : `export const KIT_KERNEL_KINDS = [\n${kinds.map(k => `  "${k}"`).join(",\n")}\n] as const;`;
  return `/* Generated by \`pnpm kit:gen\`: the kinds whose kernels the clips' module holds, in the order of KIT_KERNELS in
   video/kit-kernels.c, so a kind's place here is its kernel's there; each kernel's cost an evaluation (kit/compile.ts)
   and the share of its effect's pixels whose shadow runs past the shading's window (kitShadowRun in
   scripts/kit-gen.ts), which its clips' weight is worked out from (video.ts kitVideoWeight). */
${list}
${numberList("export const KIT_KERNEL_COSTS: readonly number[]", costs)}
${numberList("export const KIT_SHADOW_RUNS: readonly number[]", runs)}
`;
}

/** The share of a field effect's pixels whose shadow kitShade composites past its window of sheets (kit/shade.ts), its
    point more than KIT_EDGE levels above the pixel's. A pixel's can where the shadow's length times the field's slope
    (field units a D unit, the same size at any angle a view turns the design to) spans more than KIT_EDGE steps, and
    does past a step more, at the view that turns the slope toward the light. Read at 12 by 12 points over the design
    square, jittered so a tiled design cannot beat with them, the designed shape at three times of its loop: worked out
    here once and written into kernel-order.ts, where video.ts worked it out for every effect each time it started, 1.2
    to 3.4 ms an effect with a shadow in a fresh process, most of it its kernel's first compiling, 0.4 to 0.8 ms after
    (8 Nov 2026: the demo and the zen garden, a field effect the site played until 10 Nov 2026; the sandstone, with
    none, 0.1), so the clips' start grew with every effect. The shadow's length against the step alone (a D unit
    against a field's) missed the zen garden as it then stood, over levels 0.12 apart, whose shadows kitShade ran past
    its window at 29% of its pixels, and charged a shadow of 0.13 over the demo's levels 0.12 apart, of whose pixels it
    ran none so (8 Nov 2026). Sheets finer than a pixel take the run besides, a pixel spanning more than a level: no
    effect is drawn so. */
export function kitShadowRun(def: FieldEffect): number {
  const S = def.sheets;
  const shadow = S?.shadow;
  if (!S || !shadow) return 0;
  /* the levels at their closest, where the view's steps space them: its most steps' */
  const step = def.steps ? S.step * (def.steps.designed / def.steps.most) : S.step;
  const { U, tracks } = def.design(def.designedSeed);
  const F = new Float64Array(def.tracks);
  const jitter = kitRng(1);
  const h = 1 / 1024;
  const turn = 2 * Math.PI;
  let run = 0;
  for (const t of [0, def.loop / 3, (2 * def.loop) / 3]) {
    /* the phases at t, as kitFrameAt sets them */
    for (let i = 0; i < def.tracks; i++) {
      const v = tracks[i];
      const p = v.rest + v.swing * Math.sin((turn * v.cycles * t) / def.loop + v.psi);
      F[i] = p - turn * Math.floor(p / turn);
    }
    for (let i = 0; i < 12; i++)
      for (let j = 0; j < 12; j++) {
        const x = ((i + jitter()) / 12 - 0.5) / def.span;
        const y = ((j + jitter()) / 12 - 0.5) / def.span;
        const f = def.field(x, y, U, F);
        const slope = Math.hypot(def.field(x + h, y, U, F) - f, def.field(x, y + h, U, F) - f) / h;
        run += Math.min(1, Math.max(0, (shadow.distance * slope) / step - KIT_EDGE));
      }
  }
  return run / (3 * 12 * 12);
}

function kernelsFile(fields: readonly FieldEffect[], compiled: CompiledKernel[]): string {
  const kernels = fields.map(
    (def, n) =>
      `/* kit/fields/${def.kind}.ts: ${def.field.name}, cost ${compiled[n].cost} */\n${compiled[n].c}\n`
  );
  return `/* Generated by \`pnpm kit:gen\` (packages/engine/scripts/kit-gen.ts): each field effect's kernel in C, in double
   precision, as kit/compile.ts writes it from kit/fields/<kind>.ts: edit those files, never this one. video.c includes
   it; kit.h declares what the kernels call, which the clips' module defines. */
#include "kit.h"

${kernels.join("\n")}
/* every kernel, by its kind's place in kit/gen/kernel-order.ts */
static const kit_kernel KIT_KERNELS[] = {${fields.map(def => `kfield_${def.kind}`).join(", ")}};
`;
}

/** What the kit draws every field effect's pixels with besides its own file and its kernel's C: its scene, its shading
    and its CPU drawing (the clips' C past the kernel, video.c's kit_frame, counts in the clips' VIDEO_DRAWING). */
const KIT_DRAWING_SOURCES = ["kit/scene.ts", "kit/shade.ts", "kit/render.ts"] as const;

/** A field effect's drawing: the first 12 hex digits of a hash of its file (kit/fields/<kind>.ts), the kit's drawing
    (KIT_DRAWING_SOURCES) and its kernel in C as the clips' module holds it. The Worker keeps its cards, pictures and
    clips in R2 under it (apps/web server/images/cards.ts, video.ts), so a file kit:add replaces, or a change to the
    kit's drawing, keeps none drawn before, while a kind whose file and drawing stand as they were keeps its own: where
    one hand-counted key stood for every field effect, a replaced file kept answering with its old pictures until
    someone counted it up, and counting it up drew every field effect's again (8 Nov 2026). A comment changed in one of
    those files is a new drawing too: kit/compile.test.ts names the file stale until kit:gen has run. */
export function kitDrawing(def: FieldEffect, kernel: CompiledKernel): string {
  const hash = createHash("sha256");
  for (const path of [`kit/fields/${def.kind}.ts`, ...KIT_DRAWING_SOURCES])
    hash
      .update(`${path}\0`)
      .update(readFileSync(new URL(path, ENGINE_SRC)))
      .update("\0");
  return hash.update(kernel.c).digest("hex").slice(0, 12);
}

/** drawings.ts: each site effect's drawing by its kind, the demo's none, as no page plays it. */
function drawingsFile(fields: readonly FieldEffect[], compiled: CompiledKernel[]): string {
  const rows = fields.flatMap((def, n) =>
    def === demo ? [] : [`  ${def.kind}: "${kitDrawing(def, compiled[n])}"`]
  );
  return `/* Generated by \`pnpm kit:gen\` (scripts/kit-gen.ts kitDrawing): each field effect's drawing, a hash of its file, the
   kit's scene, shading and CPU drawing, and its kernel in C, which names the cards, pictures and clips the Worker keeps
   of it (apps/web server/images/cards.ts, video.ts): edit the effect's file, never this one. */
import type { KitKind } from "../kinds.ts";

export const KIT_DRAWINGS: Readonly<Record<KitKind, string>> = {
${rows.join(",\n")}
};
`;
}

/** kind-steps.ts: each site effect's steps by its kind, null where it takes none, the demo's none, as no page plays
    it. */
function stepsFile(fields: readonly FieldEffect[]): string {
  const rows = fields.flatMap(def =>
    def === demo
      ? []
      : [
          `  ${def.kind}: ${def.steps ? `{ least: ${def.steps.least}, most: ${def.steps.most}, designed: ${def.steps.designed} }` : "null"}`
        ]
  );
  return `/* Generated by \`pnpm kit:gen\` (scripts/kit-gen.ts) from each field effect's \`steps\` (kit/types.ts FieldEffect): the
   range of the view's steps an effect takes as its levels' density, null where it takes none. engine/effect.ts's
   EFFECT_KINDS reads it, which every page's start loads: edit the effect's file, never this one. */
import type { KitKind } from "../kinds.ts";
import type { KitSteps } from "../types.ts";

export const KIT_STEPS: Readonly<Record<KitKind, KitSteps | null>> = {
${rows.join(",\n")}
};
`;
}

/** Each effect's kernel compiled from its file. */
export const kitKernels = (fields: readonly FieldEffect[]): CompiledKernel[] =>
  fields.map(def => {
    const file = `kit/fields/${def.kind}.ts`;
    const source = readFileSync(new URL(file, ENGINE_SRC), "utf8");
    const { kind, uniforms, tracks } = def;
    return compileKernel(source, { name: def.field.name, kind, uniforms, tracks, file });
  });

/** Every generated file's text, by its path under packages/engine/src. */
export function kitGenerated(
  fields: readonly FieldEffect[] = KIT_FIELDS,
  compiled = kitKernels(fields)
): Map<string, string> {
  const files = new Map<string, string>();
  fields.forEach((def, n) => {
    files.set(`kit/gen/${def.kind}.ts`, kindFile(def, compiled[n]));
  });
  files.set(
    "kit/gen/kernel-order.ts",
    orderFile(
      fields.map(def => def.kind),
      compiled.map(k => k.cost),
      fields.map(kitShadowRun)
    )
  );
  files.set("video/kit-kernels.c", kernelsFile(fields, compiled));
  files.set("kit/gen/drawings.ts", drawingsFile(fields, compiled));
  files.set("kit/gen/kind-steps.ts", stepsFile(fields));
  return files;
}

if (import.meta.main) {
  const compiled = kitKernels(KIT_FIELDS);
  const files = kitGenerated(KIT_FIELDS, compiled);
  for (const [path, text] of files) {
    const url = new URL(path, ENGINE_SRC);
    let was = "";
    try {
      was = readFileSync(url, "utf8");
    } catch {}
    if (was !== text) {
      writeFileSync(url, text);
      console.log(`wrote ${path}`);
    }
  }
  /* a kind no longer compiled leaves no file behind */
  for (const name of readdirSync(new URL("kit/gen/", ENGINE_SRC)))
    if (!files.has(`kit/gen/${name}`)) {
      unlinkSync(new URL(`kit/gen/${name}`, ENGINE_SRC));
      console.log(`removed kit/gen/${name}`);
    }
  KIT_FIELDS.forEach((def, n) => {
    const { cost } = compiled[n];
    console.log(
      `${def.kind}: cost ${cost}${cost > KIT_KERNEL_BUDGET ? ", over" : " of"} the budget of ${KIT_KERNEL_BUDGET}`
    );
  });
}
